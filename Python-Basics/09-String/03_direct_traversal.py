"""
Problem: Print Characters Using Direct Traversal

Difficulty: Easy

Problem Statement:
Given a string, print each character on a new line using direct traversal.
Do not use range(), len(), or indexing.

Example:
Input:
Python

Output:
P
y
t
h
o
n

Concepts Used:
- Direct Traversal
- for loop

Pattern:
- Direct Traversal

Time Complexity:
O(n)

Space Complexity:
O(1)
"""

s = input()

# Write your code here
for ch in s:
    print(ch)