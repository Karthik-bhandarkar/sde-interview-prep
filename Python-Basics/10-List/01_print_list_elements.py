"""
Problem: Print All List Elements

Difficulty: Easy

Problem Statement:
Given a list of integers, print each element on a new line using direct traversal.

Example:
Input:
[10, 20, 30, 40]

Output:
10
20
30
40

Concepts Used:
- List
- Direct Traversal
- for loop

Pattern:
- Direct Traversal

Time Complexity:
O(n)

Space Complexity:
O(1)
"""

numbers = [10, 20, 30, 40]

# Write your code here
for num in numbers:
    print(num)